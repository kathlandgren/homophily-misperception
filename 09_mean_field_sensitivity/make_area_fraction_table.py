"""make_area_fraction_table.py — SI table: share of parameter space in the empirical range.

For the stochastic block model mean field (run_sweep_A.py), computes the fraction of the
(H_in^s, H_in^o) ∈ [0,1]² grid where β_overall lies in the empirical range [0.21, 0.30],
for every H_out and f_s, and writes the LaTeX tabular used in the SI (\\label{tab:area-frac}).
The manuscript baseline row (H_out = 0.3) is set in bold.

Data required: run run_sweep_A.py first (09_mean_field_sensitivity/output/).

Output: tables/area_fraction_table.tex

Usage:
    python 09_mean_field_sensitivity/make_area_fraction_table.py
"""

from decimal import Decimal, ROUND_HALF_UP

import numpy as np
from pyprojroot import here

# Fixed settings
BETA_EMP_LO, BETA_EMP_HI = 0.21, 0.30
BOLD_H_OUT = 0.3
FS_HEADER  = {0.5: '1/2', 0.6667: '2/3', 0.8: '4/5'}

DATA_DIR = here() / '09_mean_field_sensitivity' / 'output'
OUT_PATH = here() / 'tables' / 'area_fraction_table.tex'


def load():
    data = {}
    for f in sorted(DATA_DIR.glob('sweep_A_*.npz')):
        d = np.load(f)
        data[(round(float(d['H_out']), 2), round(float(d['f_s']), 4))] = d['beta_overall']
    return data


def main():
    data = load()
    h_outs = sorted({k[0] for k in data})
    fss    = sorted({k[1] for k in data})

    lines = [
        '% area_fraction_table.tex — generated by 09_mean_field_sensitivity/make_area_fraction_table.py',
        r'\begin{tabular}{lrrr}',
        r'\toprule',
        ' & ' + ' & '.join(f'$f_s={FS_HEADER[fs]}$' for fs in fss) + r' \\',
        r'$H_{\text{out}}$ & & & \\',
        r'\midrule',
    ]
    for h in h_outs:
        cells = [f'{h:.1f}']
        for fs in fss:
            beta = data[(h, fs)]
            frac = float(((beta >= BETA_EMP_LO) & (beta <= BETA_EMP_HI)).mean())
            # 4 decimal places, then rounded half up to 3, as in the table in the SI
            cells.append(str(Decimal(f'{frac:.4f}').quantize(Decimal('0.001'), rounding=ROUND_HALF_UP)))
        if np.isclose(h, BOLD_H_OUT):
            cells = [rf'\textbf{{{c}}}' for c in cells]
        lines.append(' & '.join(cells) + r' \\')
    lines += [r'\bottomrule', r'\end{tabular}']

    OUT_PATH.parent.mkdir(exist_ok=True)
    OUT_PATH.write_text('\n'.join(lines) + '\n')
    print(f'Saved {OUT_PATH}')


if __name__ == '__main__':
    main()
